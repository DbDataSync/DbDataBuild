#!/usr/bin/env python3
"""Makes docs/research/function-matrix.md from the CSV files scripts/function-matrix.sh wrote (nothing is typed in by hand except the findings
section, which is read from scripts/function-matrix-findings.md when it exists). Usage: function-matrix-report.py [dir]  (default docs/research)."""
import csv, os, sys, collections

d = sys.argv[1] if len(sys.argv) > 1 else "docs/research"
funcs = list(csv.DictReader(open(os.path.join(d, "function-matrix.csv"), encoding="utf-8")))
ovl = list(csv.DictReader(open(os.path.join(d, "function-matrix-overloads.csv"), encoding="utf-8")))
tables = list(csv.DictReader(open(os.path.join(d, "function-matrix-table-functions.csv"), encoding="utf-8")))
meta = dict(l.rstrip("\n").split("=", 1) for l in open(os.path.join(d, "function-matrix-meta.txt"), encoding="utf-8") if "=" in l)
here = os.path.dirname(os.path.abspath(__file__))
findings_path = os.path.join(here, "function-matrix-findings.md")
findings = open(findings_path, encoding="utf-8").read() if os.path.exists(findings_path) else ""

ENG = [("sqlserver", "SQL Server"), ("postgres", "PostgreSQL")]
SEVERITY = ["lowerer error", "differs", "engine error", "refused", "works", "arg type unsupported", "not probed"]

# "common types": the overloads whose parameters are all among the types models use (integers up to BIGINT, FLOAT, DOUBLE, DECIMAL, text, boolean, DATE, TIMESTAMP, or a generic value);
# a function is judged on these in the cross-check, so that an overload over INTERVAL, TIME, BLOB, UUID, HUGEINT or a list does not decide it
COMMON = {"SMALLINT", "INTEGER", "BIGINT", "FLOAT", "DOUBLE", "DECIMAL", "VARCHAR", "BOOLEAN", "DATE", "TIMESTAMP", "ANY", "T", "K", "V", "NULL", "..."}

def params_of(sig):
    inner = sig[sig.index("(") + 1: sig.rindex(") ->")]
    parts, depth, cur = [], 0, ""
    for ch in inner:
        if ch in "([": depth += 1
        if ch in ")]": depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur.strip()); cur = ""
        else:
            cur += ch
    if cur.strip(): parts.append(cur.strip())
    return [p_.replace("... ", "").strip() for p_ in parts]

def is_common(r):
    if r["kind"] == "macro": return True
    return all(p_ in COMMON for p_ in params_of(r["signature"]) if p_)
ORDER = ["works", "differs", "engine error", "refused", "lowerer error", "arg type unsupported", "not probed"]
STATIC = ["same", "rewritten", "refused", "error", "not-probed"]

core = {}
for r in ovl:
    if is_common(r):
        core.setdefault(r["canonical"], []).append(r)
for f in funcs:
    for e, _ in ENG:
        rs = core.get(f["function"], [])
        outs = [r[e + "_outcome"] for r in rs]
        f[e + "_core"] = next((o for o in SEVERITY if o in outs), "n/a")

def esc(s):
    return s.replace("|", "\\|").replace("\n", " ")

def clip(s, n=170):
    s = " ".join(s.split())
    return s if len(s) <= n else s[: n - 3] + "..."

out = []
w = out.append
w("# Function matrix: every DuckDB function on SQL Server and PostgreSQL\n")
w("*Generated by `scripts/function-matrix.sh` (data: `function-matrix*.csv` in this folder; report: `scripts/function-matrix-report.py`). Do not edit by hand: rerun the script.*\n")
w("## What was measured, and what was not\n")
w(f"- **Functions**: `duckdb_functions()` of the DuckDB the tool ships (**{meta.get('duckdb', '?')}** through DuckDB.NET): scalar, aggregate and window functions, operators (labelled by the symbol), and the macros that DuckDB ships (`main` and `pg_catalog`). {len(ovl)} overloads, {len(funcs)} functions (an alias is in the row of the function it points at). Table functions and pragmas are listed in `function-matrix-table-functions.csv` ({len(tables)} rows) and not probed.")
w("- **Static outcome** (nothing is run): the tool's own pipeline on a minimal query per overload: DuckDB's bound plan, `PlanLowerer`, `TargetRules`, the matrix lint on the rewritten query, polyglot's transpile, the target's own parser (ScriptDOM or polyglot's PostgreSQL parse). `same` = the function's name (or operator) is still a call in the text sent to the engine and no target rule fired; `rewritten` = other text; `refused` = the lowerer refused (DDB-324) or the lint/parser reported an error (the code is in the CSV); `error` = the pipeline crashed or the transpile failed (a bug candidate); `not probed` = no query could be built (reason in the CSV). `same`/`rewritten` is a name heuristic: it does not say the text is right.")
w("- **Dynamic outcome** (verified on a real engine: **SQL Server 2022**, `targets.sqlserver.version` 16, and **PostgreSQL 17**, both docker, loopback): for what lowers, the text the tool would send is run and compared with DuckDB's answer on the probe table (8 rows: negatives, zero, NULL, empty string, accented and non-BMP text, a leap day, month ends, the largest INT; a second argument comes from a second copy of the table, so every pair of rows is tried; date parts, formats and the like are one variant each). `works` = same values and same kind of type (exact number / floating / text / date ...) on every row where DuckDB answers; `differs` = runs but a value, the type kind, or whether it raises differs (one example in the data); `engine error` = the engine rejects the text or raises on every row DuckDB answers. Time, randomness, session functions and order-dependent aggregates are only checked for running (`values_compared = run only`).")
w("- **Fabric** was **not run** (no Fabric engine exists here). Its column says only whether the text the tool renders for Fabric equals the SQL Server text.")
w("- **Caveats**: one probe table, so a function that is wrong only for inputs outside it shows `works`; an argument type is a cast of a probe column (a TINYINT argument is `CAST(j AS TINYINT)`; SQL Server's `tinyint` is unsigned, so negative samples raise there, which is a finding about the type mapping, listed against every TINYINT overload); a function with several valid spellings of an argument is `differs` if any one differs (the variants that fail are named in the detail); the outcome of a function is the worst of its overloads and variants (counts are variants); a function that DuckDB rejects with my generated arguments is `not probed` with DuckDB's message; macros have no parameter types, so the argument types were found by trying; `age` and other INTERVAL results are compared as (months, days, microseconds).\n")

# ---- summary ----
w("## Summary\n")
w("Functions by worst outcome of any overload (a function counts once):\n")
w("| Outcome | " + " | ".join(n for _, n in ENG) + " |")
w("|---|" + "---|" * len(ENG))
for o in ORDER:
    w(f"| {o} | " + " | ".join(str(sum(1 for f in funcs if f[e + '_outcome'] == o)) for e, _ in ENG) + " |")
w(f"| **total** | " + " | ".join(str(len(funcs)) for _ in ENG) + " |\n")
w("The same, judged only on the overloads over common types (integers up to BIGINT, FLOAT, DOUBLE, DECIMAL, text, boolean, DATE, TIMESTAMP, generic values; macros always): an overload over INTERVAL, TIME, BLOB, UUID, HUGEINT or a list does not decide the function.\n")
w("| Outcome (common types) | " + " | ".join(n for _, n in ENG) + " |")
w("|---|" + "---|" * len(ENG))
for o in ORDER + ["n/a"]:
    w(f"| {o} | " + " | ".join(str(sum(1 for f in funcs if f[e + '_core'] == o)) for e, _ in ENG) + " |")
w("")
w("Overloads by outcome:\n")
w("| Outcome | " + " | ".join(n for _, n in ENG) + " |")
w("|---|" + "---|" * len(ENG))
for o in ORDER:
    w(f"| {o} | " + " | ".join(str(sum(1 for r in ovl if r[e + '_outcome'] == o)) for e, _ in ENG) + " |")
w(f"| **total** | " + " | ".join(str(len(ovl)) for _ in ENG) + " |\n")
w("Overloads by static outcome (before anything is run):\n")
w("| Static | " + " | ".join(n for _, n in ENG) + " |")
w("|---|" + "---|" * len(ENG))
for o in STATIC:
    w(f"| {o} | " + " | ".join(str(sum(1 for r in ovl if (r[e + '_static'] or 'not-probed') == o)) for e, _ in ENG) + " |")
w("")
by_kind = collections.Counter((f["kind"], f["sqlserver_outcome"], f["postgres_outcome"]) for f in funcs)
w("Functions that work on both engines, by kind:\n")
w("| Kind | works on both | not on at least one |")
w("|---|---|---|")
kinds = sorted(set(f["kind"] for f in funcs))
for k in kinds:
    fk = [f for f in funcs if f["kind"] == k]
    ok = sum(1 for f in fk if f["sqlserver_outcome"] == "works" and f["postgres_outcome"] == "works")
    w(f"| {k} | {ok} | {len(fk) - ok} |")
w("")

if findings:
    w(findings.rstrip() + "\n")

# ---- the matrix ----
def cell(f, e):
    o = f[e + "_outcome"]
    if o == "works":
        return "works"
    s = f"**{o}** ({f[e + '_counts']}; common types: {f[e + '_core']})"
    if f[e + "_detail"]:
        s += ": " + clip(f[e + "_detail"])
    return s

def row(f):
    name = f["function"].replace("`", "")
    al = f" (alias: {f['aliases']})" if f["aliases"] else ""
    return f"| `{esc(name)}`{esc(al)} | {f['kind']} | {esc(cell(f, 'sqlserver'))} | {esc(cell(f, 'postgres'))} | {esc(f['fabric'])} |"

def not_working(f):
    return any(f[e + "_outcome"] != "works" for e, _ in ENG)

loud = [f for f in funcs if not_working(f) and any(f[e + "_outcome"] in ("differs", "lowerer error") for e, _ in ENG)]
errs = [f for f in funcs if not_working(f) and f not in loud and any(f[e + "_outcome"] == "engine error" for e, _ in ENG)]
refused = [f for f in funcs if not_working(f) and f not in loud and f not in errs and any(f[e + "_outcome"] == "refused" for e, _ in ENG)]
unprobed = [f for f in funcs if not_working(f) and f not in loud and f not in errs and f not in refused]

HEAD = ["| Function | Kind | SQL Server 2022 | PostgreSQL 17 | Fabric |", "|---|---|---|---|---|"]
w("## The matrix: functions that do not fully work on at least one engine\n")
w("Cells: the worst outcome over the function's overloads and variants, the count of variants per outcome, and the first reason or example (the full text, every overload, the texts sent and the lint codes are in `function-matrix-overloads.csv`). `works` on one side means every probed overload matched DuckDB on that engine.\n")
w(f"### A. Runs but gives a different value, or the lowerer failed ({len(loud)} functions)\n")
w("\n".join(HEAD + [row(f) for f in loud]) + "\n")
w(f"### B. Engine rejects the text the tool sends (nothing silent) ({len(errs)} functions)\n")
w("\n".join(HEAD + [row(f) for f in errs]) + "\n")
w(f"### C. Refused by the tool (DDB-324 or a lint error) on at least one engine, otherwise working ({len(refused)} functions)\n")
w("\n".join(HEAD + [row(f) for f in refused]) + "\n")
w(f"### D. Could not be probed ({len(unprobed)} functions)\n")
w("\n".join(HEAD + [row(f) for f in unprobed]) + "\n")

# ---- cross-check against the support matrix ----
import yaml
w("## Cross-check with `matrix/constructs.yml`\n")
rows = yaml.safe_load(open(os.path.join(here, "..", "matrix", "constructs.yml"), encoding="utf-8"))
by_name = {}
for f in funcs:
    by_name[f["function"].lower()] = f
    for a in f["aliases"].split():
        by_name[a.lower()] = f
OK = {"native", "translated", "emulated", "approximated"}
def matrix_min_version(r, e):
    entry = (r.get(e) or r.get("tsql")) if e == "sqlserver" else r.get(e)
    return (entry or {}).get("min_version")
def matrix_status(r, e):
    entry = r.get(e) or r.get("tsql") if e == "sqlserver" else r.get(e)
    return (entry or {}).get("status", "-")
w("A matrix row that names a function (`fn:` or `node:` detection) against what was measured here on the common-type overloads. **Disagrees** = the row says the construct works on that engine (native, translated, emulated or approximated) and the probe shows a function that does not run or gives other values, or the row says unsupported and the probe shows it works. The rows are decisions for the owner; the matrix was not edited.\n")
w("| Row | Function | SQL Server: row says / measured | PostgreSQL: row says / measured | Verdict |")
w("|---|---|---|---|---|")
for r in rows:
    det = r.get("detect")
    det = [det] if isinstance(det, str) else (det or [])
    names = []
    for dd in det:
        k, _, n = dd.partition(":")
        if k in ("fn", "node"):
            names.append(n.lower())
    seen = set()
    for n in names:
        f = by_name.get(n)
        if not f or f["function"] in seen:
            continue
        seen.add(f["function"])
        verdicts = []
        cells = []
        for e, label in ENG:
            ms = matrix_status(r, e)
            o = f[e + "_core"] if f[e + "_core"] != "n/a" else f[e + "_outcome"]
            cells.append(f"{ms} / {o}")
            if matrix_min_version(r, e) and o == "refused":
                cells[-1] += f" (needs version {matrix_min_version(r, e)}; the run is at 16)"      # the row is right: the lint refuses below the version
            elif ms in ("native", "translated") and o != "works":
                verdicts.append(f"{label}: row says {ms}, measured {o}")
            elif ms == "approximated" and o not in ("works", "differs"):
                verdicts.append(f"{label}: row says approximated, measured {o}")
            elif ms == "unsupported" and o == "works" and "rule" in str((r.get(e) or r.get("tsql") or {}).get("note", "")) + str((r.get(e) or {}).get("note", "")):
                cells[-1] += " (the lowered text is rewritten by a target rule)"
            elif ms == "unsupported" and o == "works":
                verdicts.append(f"{label}: row says unsupported, measured works")
        w(f"| `{r['id']}` | `{esc(f['function'])}` | {cells[0]} | {cells[1]} | {'; '.join(verdicts) if verdicts else 'agrees'} |")
w("")
uncovered = [f for f in funcs if f["sqlserver_outcome"] == "works" and f["postgres_outcome"] == "works" and "DDB-305" in (f["sqlserver_lint"] + " " + f["postgres_lint"])]
w(f"Functions that **work** on both engines against DuckDB's answer but have **no matrix row** and are not in `covered.yml` (the lint reports them as DDB-305): **{len(uncovered)}**.\n")
w("<details><summary>list</summary>\n\n" + ", ".join(f"`{esc(f['function'])}`" for f in uncovered) + "\n\n</details>\n")
partial = [f for f in funcs if (f["sqlserver_outcome"] == "works") != (f["postgres_outcome"] == "works") and "DDB-305" in (f["sqlserver_lint"] + " " + f["postgres_lint"])]
w(f"Functions that work on exactly one of the two engines and carry no matrix row: **{len(partial)}** (in the matrix above).\n")

w("## Table functions and pragmas (listed, not probed)\n")
w("The tool lowers only integer `generate_series` and `range` (DESIGN 7.6) and refuses every other table function (DDB-324). Names: " + ", ".join(sorted(set(f"`{t['name']}`" for t in tables if t["kind"] == "table"))) + ".\n")

open(os.path.join(d, "function-matrix.md"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("wrote", os.path.join(d, "function-matrix.md"))
